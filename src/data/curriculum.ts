// The curriculum: which words and verbs each chapter teaches. This is the only
// hand-written word data in the game — meanings, gender, forms, synonyms,
// Spain vs Latin American variants and example sentences all come from
// Wiktionary and Tatoeba (see scripts/data, run `npm run data`).
//
// A word is its Spanish lemma, optionally with an emoji and options:
//   sense   — a word from the English meaning to teach, when Wiktionary's first sense isn't it
//   en      — the English prompt, when Wiktionary lacks the phrase or words it unhelpfully
//             ("de nada" is “it's nothing” there; we ask for “you're welcome”)
//   lookup  — the Wiktionary entry to use when it differs from the word ("mola" → "molar")
//   both    — show both genders ("el amigo / la amiga")
//   trap    — for false friends: the English look-alike and how to really say it
//   id      — keeps an older id when two words would collide

export type Pos = 'noun' | 'verb' | 'adj' | 'adv' | 'phrase' | 'num';

export interface WordOptions {
  sense?: string;
  en?: string;
  lookup?: string;
  both?: boolean;
  trap?: [string, string];
  id?: string;
}

export type CurriculumWord = string | [lemma: string, emoji: string, options?: WordOptions];

export interface Lesson {
  chapter: number;
  category: string;
  pos: Pos;
  /** Advanced words, only practised at the B1 level. */
  level?: 'b1';
  words: CurriculumWord[];
}

export interface VerbLesson {
  chapter: number;
  /** An infinitive, or [infinitive, sense] when Wiktionary's first meaning isn't the one taught. */
  verbs: (string | [string, string])[];
}

function lesson(chapter: number, category: string, pos: Pos, words: CurriculumWord[], level?: 'b1'): Lesson {
  return { chapter, category, pos, words, level };
}

function verbs(chapter: number, list: VerbLesson['verbs']): VerbLesson {
  return { chapter, verbs: list };
}

